"""Atomic rollout-boundary snapshots for long CPU or CUDA training runs."""
import json
import os
import pickle
import random
from collections import deque
from pathlib import Path

import numpy as np
import torch


def _actor_state(mac):
    state = {"agents": [agent.state_dict() for agent in mac.agents]}
    if hasattr(mac, "encoder"):
        state["encoder"] = mac.encoder.state_dict()
    if getattr(mac, "node_readouts", None) is not None:
        state["node_readouts"] = mac.node_readouts.state_dict()
    return state


def _restore_actor(mac, state):
    for agent, values in zip(mac.agents, state["agents"]):
        agent.load_state_dict(values)
    if "encoder" in state:
        mac.encoder.load_state_dict(state["encoder"])
    if "node_readouts" in state:
        mac.node_readouts.load_state_dict(state["node_readouts"])


def _learner_state(learner):
    state = {
        "actor": _actor_state(learner.mac),
        "critic": learner.Vnet.state_dict(),
        "target_critic": learner.target_Vnet.state_dict(),
        "actor_optimizer": learner.optimiser.state_dict(),
        "critic_optimizer": learner.Vnet_optimiser.state_dict(),
        "mixer": learner.mixer.state_dict() if learner.mixer is not None else None,
        "training_steps": learner.training_steps,
        "last_target_update_step": learner.last_target_update_step,
        "last_target_update_episode": learner.last_target_update_episode,
        "log_stats_t": learner.log_stats_t,
        "logger_latest": learner.logger.latest.copy(),
    }
    for name in ("rew_ms", "ret_ms"):
        if hasattr(learner, name):
            obj = getattr(learner, name)
            state[name] = {key: getattr(obj, key) for key in ("mean", "var", "count")}
    if hasattr(learner, "effect_optimizer"):
        state["effect_optimizer"] = learner.effect_optimizer.state_dict()
    return state


def _restore_learner(learner, state):
    _restore_actor(learner.mac, state["actor"])
    learner.Vnet.load_state_dict(state["critic"])
    learner.target_Vnet.load_state_dict(state["target_critic"])
    learner.optimiser.load_state_dict(state["actor_optimizer"])
    learner.Vnet_optimiser.load_state_dict(state["critic_optimizer"])
    if state["mixer"] is not None:
        learner.mixer.load_state_dict(state["mixer"])
    for name in ("training_steps", "last_target_update_step",
                 "last_target_update_episode", "log_stats_t"):
        setattr(learner, name, state[name])
    learner.logger.latest = state["logger_latest"]
    for name in ("rew_ms", "ret_ms"):
        if name in state:
            obj = getattr(learner, name)
            for key, value in state[name].items():
                if torch.is_tensor(value):
                    value = value.to(learner.args.device)
                setattr(obj, key, value)
    if "effect_optimizer" in state:
        learner.effect_optimizer.load_state_dict(state["effect_optimizer"])


def capture_environments(envs):
    if all(hasattr(env, "submit_snapshot") for env in envs):
        for env in envs:
            env.submit_snapshot()
        return [env.receive_snapshot() for env in envs]
    return [pickle.dumps(env, protocol=pickle.HIGHEST_PROTOCOL) for env in envs]


def save_resume(run, learner, replay, envs, progress, record):
    """Commit the state only after an entire rollout and its updates complete."""
    run = Path(run)
    state = {
        "version": 2,
        "learner": _learner_state(learner),
        "environments": capture_environments(envs),
        "replay_files": [path.name for path in replay.files],
        "replay_sequence": replay.sequence,
        "progress": progress,
        "record": record,
        "python_rng": random.getstate(),
        "numpy_rng": np.random.get_state(),
        "torch_rng": torch.get_rng_state(),
        "torch_cuda_rng": (torch.cuda.get_rng_state_all()
                           if learner.args.use_cuda else None),
    }
    temporary = run / "resume.pt.tmp"
    torch.save(state, temporary)
    os.replace(temporary, run / "resume.pt")


def read_resume(run):
    # Only load snapshots generated by this project in the user's local run dir.
    return torch.load(Path(run) / "resume.pt", map_location="cpu", weights_only=False)


def restore_resume(run, state, learner, replay):
    if state["version"] not in (1, 2):
        raise ValueError("Unsupported resume snapshot version")
    _restore_learner(learner, state["learner"])
    names = state["replay_files"]
    if len(names) > replay.capacity or len(names) != len(set(names)):
        raise ValueError("Invalid replay manifest")
    replay.files = deque(replay.directory / name for name in names)
    replay.sequence = state["replay_sequence"]
    if any(Path(name).name != name or Path(name).suffix != ".pt" for name in names):
        raise ValueError("Unsafe replay manifest")
    if any(not path.is_file() for path in replay.files):
        raise FileNotFoundError("Resume replay is incomplete")
    wanted = set(names)
    root = replay.directory.resolve()
    for path in replay.directory.glob("*.pt"):
        if path.name not in wanted:
            if not path.resolve().is_relative_to(root):
                raise ValueError("Replay file resolves outside its directory")
            path.unlink()
    random.setstate(state["python_rng"])
    np.random.set_state(state["numpy_rng"])
    torch.set_rng_state(state["torch_rng"])
    if learner.args.use_cuda:
        cuda_rng = state.get("torch_cuda_rng")
        if cuda_rng is None:
            raise ValueError("CUDA snapshot is missing CUDA RNG state")
        if len(cuda_rng) != torch.cuda.device_count():
            raise ValueError("CUDA device count changed since the snapshot")
        torch.cuda.set_rng_state_all(cuda_rng)
    metrics = Path(run) / "metrics.jsonl"
    if metrics.exists():
        lines = [json.loads(line) for line in metrics.read_text(encoding="utf-8").splitlines()]
        last_step = lines[-1]["t_env"] if lines else -1
    else:
        last_step = -1
    step = state["progress"]["t_env"]
    if last_step > step:
        raise ValueError("Metrics are ahead of the committed resume snapshot")
    if last_step < step:
        with metrics.open("a", encoding="utf-8") as stream:
            stream.write(json.dumps(state["record"]) + "\n")
    return state["progress"]
